import { readFile, writeFile, cp } from 'node:fs/promises';
const names = ['sparkle', 'heart', 'arrow-up-right', 'arrow-left', 'arrow-right', 'arrow-down', 'flower', 'flower-2', 'sprout', 'audio-lines', 'plus', 'minus', 'rotate-ccw', 'box', 'house', 'columns-3', 'coffee', 'panels-top-left', 'sun', 'x', 'menu'];
let css = '/* Generated by scripts/prepare-icons.mjs from lucide-static; do not edit. */\n:root {\n';
for (const name of names) {
  const svg = await readFile(`node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  css += `  --icon-${name}: url("data:image/svg+xml,${encodeURIComponent(svg.trim()).replaceAll("'", '%27')}");\n`;
}
css += '}\n.icon { display: inline-block; width: 1em; height: 1em; flex: 0 0 auto; vertical-align: -.125em; background-color: currentColor; mask: var(--icon) center / contain no-repeat; }\n';
for (const name of names) css += `.icon-${name} { --icon: var(--icon-${name}); }\n`;
await writeFile('shared/icons.css', css);
await cp('node_modules/lucide-static/LICENSE', 'shared/LUCIDE-LICENSE.txt');
console.log(`Prepared ${names.length} Lucide icons`);
